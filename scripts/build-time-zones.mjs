#!/usr/bin/env node
/**
 * Builds src/lib/time-zones.ts: which country each IANA time zone belongs to.
 *
 * The cold read names the visitor's country from their clock's time zone. Browsers
 * don't expose that mapping, so we ship it. It comes from the tz database itself:
 * zone.tab gives each zone's country, and the database's links resolve the old and
 * alternative names some browsers still report (Asia/Calcutta, US/Eastern, ...).
 *
 *   node scripts/build-time-zones.mjs [zoneinfo directory]
 *
 * The directory defaults to /usr/share/zoneinfo and needs zone.tab and tzdata.zi.
 * Re-run it when the tz database adds or renames zones; the result is committed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2] ?? '/usr/share/zoneinfo';
const out = new URL('../src/lib/time-zones.ts', import.meta.url);

const read = (name) => readFileSync(join(dir, name), 'utf8');
const version = /^# version (\S+)/m.exec(read('tzdata.zi'))?.[1] ?? 'unknown';

/** zone -> ISO 3166 country code */
const country = new Map();
for (const line of read('zone.tab').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [code, , zone] = line.split('\t');
  country.set(zone, code);
}

// Links: "L target alias". Resolve each alias through its target, following chains.
const links = new Map();
for (const line of read('tzdata.zi').split('\n')) {
  if (!line.startsWith('L ')) continue;
  const [, target, alias] = line.split(' ');
  links.set(alias, target);
}
for (const alias of links.keys()) {
  if (country.has(alias)) continue;
  let target = links.get(alias);
  for (let hops = 0; target && !country.has(target) && hops < 5; hops++) target = links.get(target);
  const code = target ? country.get(target) : undefined;
  if (code) country.set(alias, code);
}

// Every zone the browser's own Intl data knows about should be covered.
const missing = Intl.supportedValuesOf('timeZone').filter((z) => !country.has(z) && !z.startsWith('Etc/') && z !== 'UTC');
if (missing.length) console.warn(`No country for: ${missing.join(', ')}`);

const byCountry = new Map();
for (const [zone, code] of [...country].sort(([a], [b]) => a.localeCompare(b))) {
  if (!byCountry.has(code)) byCountry.set(code, []);
  byCountry.get(code).push(zone);
}

const rows = [...byCountry]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, zones]) => `  ${code}: '${zones.join(' ')}',`)
  .join('\n');

writeFileSync(
  out,
  `// Generated by scripts/build-time-zones.mjs from tz database ${version}. Do not edit by hand.

/** ISO 3166 country code -> the IANA time zones (and their old aliases) in it, space-separated. */
const ZONES_BY_COUNTRY: Record<string, string> = {
${rows}
};

let index: Map<string, string> | null = null;

/** "Asia/Karachi" gives "PK". Zones that aren't places (UTC, Etc/GMT+5) give null. */
export function countryOfTimeZone(timeZone: string): string | null {
  if (!index) {
    index = new Map();
    for (const [code, zones] of Object.entries(ZONES_BY_COUNTRY)) for (const zone of zones.split(' ')) index.set(zone, code);
  }
  return index.get(timeZone) ?? null;
}
`,
);

console.log(`Wrote ${country.size} zones in ${byCountry.size} countries (tz ${version}).`);
